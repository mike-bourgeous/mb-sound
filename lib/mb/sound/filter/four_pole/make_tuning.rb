#!/usr/bin/env ruby
# Generates the four-pole's and diode ladder's edge tuning tables
# (+tuning: :edge+): lib/mb/sound/filter/four_pole/tuning_tables.rb and
# ext/mb/sound/include/mb_four_pole_tuning.h, the same numbers for the Ruby
# mirror and the C kernels (see FourPole::Tuning and TuningAnalysis).
#
#     bundle exec ruby lib/mb/sound/filter/four_pole/make_tuning.rb [--check]
#
# --check compares the files with freshly generated ones instead of writing
# (exit status 1 if they differ).  About 20 seconds.

$LOAD_PATH.unshift File.expand_path('../../../..', __dir__)
require 'mb/sound'
require 'mb/sound/filter/four_pole/tuning_analysis'

module MB
  module Sound
    class Filter
      class FourPole
        # Builds the tuning tables (see make_tuning.rb).
        module TuningGenerator
          TA = TuningAnalysis
          ROOT = File.expand_path('../../../../..', __dir__)
          RUBY_PATH = File.join(ROOT, 'lib/mb/sound/filter/four_pole/tuning_tables.rb')
          C_PATH = File.join(ROOT, 'ext/mb/sound/include/mb_four_pole_tuning.h')

          # Step for the numeric derivatives (in x).
          H = 1e-5

          # One mode's table (a Tuning::MODES entry): [m, dm/dx / SEGMENTS]
          # at x = i / SEGMENTS.
          def self.table(mode, segments = Tuning::SEGMENTS)
            sc = ->(x) { TA.scale(mode, x) }
            (0..segments).flat_map do |i|
              x = i.to_f / segments
              v = i == segments ? 1.0 : sc.(x)
              d =
                if i == 0
                  (-3 * v + 4 * sc.(H) - sc.(2 * H)) / (2 * H)
                elsif i == segments
                  (3.0 - 4 * sc.(1 - H) + sc.(1 - 2 * H)) / (2 * H)
                else
                  (sc.(x + H) - sc.(x - H)) / (2 * H)
                end
              [v, d / segments]
            end
          end

          def self.tables
            Tuning::MODES.to_h { |mode| [mode, table(mode)] }
          end

          def self.number(v)
            s = format('%.17g', v)
            s.include?('.') || s.include?('e') ? s : "#{s}.0"
          end

          def self.ruby_source(tables)
            rows = tables.map do |mode, t|
              lines = t.each_slice(4).map { |s| "              #{s.map { |v| number(v) }.join(', ')}," }
              "            #{mode}: [\n#{lines.join("\n")}\n            ].freeze,"
            end

            <<~RUBY
              # Generated by lib/mb/sound/filter/four_pole/make_tuning.rb; do not edit.
              # The edge tuning's tables (see FourPole::Tuning): for each mode,
              # [m, dm/dx / SEGMENTS] at x = i / SEGMENTS, i = 0..SEGMENTS.
              module MB
                module Sound
                  class Filter
                    class FourPole < Filter
                      module Tuning
                        TABLES = {
              #{rows.join("\n")}
                        }.freeze
                      end
                    end
                  end
                end
              end
            RUBY
          end

          def self.c_source(tables)
            rows = tables.map do |mode, t|
              lines = t.each_slice(4).map { |s| "\t\t#{s.map { |v| number(v) }.join(', ')}," }
              "\t// #{mode}\n\t{\n#{lines.join("\n")}\n\t},"
            end

            <<~C
              /*
               * Generated by lib/mb/sound/filter/four_pole/make_tuning.rb; do not edit.
               * The four-pole's and diode ladder's edge tuning tables (see
               * fp_tuning_scale in mb_four_pole.h and FourPole::Tuning in Ruby): for
               * each tuning 1..#{tables.length} (#{tables.keys.join(', ')}), [m, dm/dx / FP_TUNING_SEGMENTS]
               * at x = i / FP_TUNING_SEGMENTS, i = 0..FP_TUNING_SEGMENTS.
               */
              #ifndef MB_FOUR_POLE_TUNING_H
              #define MB_FOUR_POLE_TUNING_H

              #define FP_TUNING_SEGMENTS #{Tuning::SEGMENTS}
              #define FP_TUNING_COUNT #{tables.length}

              static const double fp_tuning_tables[FP_TUNING_COUNT][2 * (FP_TUNING_SEGMENTS + 1)] = {
              #{rows.join("\n")}
              };

              #endif
            C
          end
        end
      end
    end
  end
end

if $0 == __FILE__
  g = MB::Sound::Filter::FourPole::TuningGenerator
  tables = g.tables
  files = { g::RUBY_PATH => g.ruby_source(tables), g::C_PATH => g.c_source(tables) }
  if ARGV.include?('--check')
    stale = files.reject { |path, text| File.exist?(path) && File.read(path) == text }.keys
    stale.each { |path| puts "Out of date: #{path}" }
    exit(stale.empty? ? 0 : 1)
  end
  files.each do |path, text|
    File.write(path, text)
    puts "Wrote #{path}"
  end
end
