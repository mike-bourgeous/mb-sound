#!/usr/bin/env ruby
# Regenerates lib/mb/sound/plot/font.rb (the bitmap font of Plot::Image)
# from DejaVu Sans Mono 12 px, drawn by ffmpeg's drawtext filter.  Not
# loaded by the library; run by hand:
#
#     ruby lib/mb/sound/plot/make_font.rb [/path/to/DejaVuSansMono.ttf]
#
# DejaVu fonts are under the Bitstream Vera license (free to embed and
# modify, including bitmap derivatives).

# Specs that require every file under lib/ (graph_sweep_spec) must not
# regenerate the font
return unless __FILE__ == $PROGRAM_NAME

require 'tmpdir'

FONT = ARGV[0] || '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf'
CHARS = ((32..126).map(&:chr) + ['µ', '·', '…']).freeze
W = 8
H = 16

Dir.mktmpdir do |dir|
  filters = CHARS.each_with_index.map { |c, i|
    File.write(File.join(dir, "c#{i}.txt"), c)
    "drawtext=fontfile=#{FONT}:textfile=#{dir}/c#{i}.txt:x=#{i * W}:y=1:fontsize=12:fontcolor=white:expansion=none:y_align=font"
  }
  File.write(File.join(dir, 'filter.txt'), filters.join(','))
  raw = File.join(dir, 'font.gray')
  system('ffmpeg', '-v', 'error', '-y', '-f', 'lavfi', '-i', "color=c=black:s=#{CHARS.length * W}x#{H}:d=1",
    '-filter_complex_script', File.join(dir, 'filter.txt'), '-frames:v', '1', '-f', 'rawvideo', '-pix_fmt', 'gray', raw, exception: true)
  pixels = File.binread(raw).bytes
  stride = CHARS.length * W

  glyphs = CHARS.each_with_index.map { |c, i|
    nibbles = (0...H).flat_map { |y| (0...W).map { |x| (pixels[y * stride + i * W + x] / 17.0).round.to_s(16) } }.join
    "        #{c.inspect} => '#{nibbles}',"
  }

  File.write(File.join(__dir__, 'font.rb'), <<~RUBY)
    # Generated by lib/mb/sound/plot/make_font.rb from DejaVu Sans Mono 12 px
    # (Bitstream Vera license).  Do not edit by hand.
    module MB
      module Sound
        module Plot
          module Image
            # #{W}x#{H} glyphs as 4-bit alpha, row by row (one hex digit per pixel).
            module Font
              WIDTH = #{W}
              HEIGHT = #{H}
              GLYPHS = {
    #{glyphs.map { |g| '            ' + g.strip }.join("\n")}
              }.freeze
            end
          end
        end
      end
    end
  RUBY
end
