# The design notes index (docs-split-1, 2026-10-30): design/notes/README.md
# and CLAUDE.md's topic map are generated from the summary block each note
# owns, so the architecture summary can't drift from the notes.
#
#   <!-- summary -->
#   3-5 lines: what the subsystem is, its entry points, the rules that bind
#   its users.
#   <!-- /summary -->
#
# `rake docs:index` writes both; spec/docs_index_spec.rb fails while either is
# stale, while a note lacks a summary or a group, while a term of
# spec/docs/architecture_terms.txt appears nowhere, and skips (a visible
# warning, not a failure) while CLAUDE.md is over BUDGET.  Loaded by the
# Rakefile and the spec, without mb-sound.
module DocsIndex
  ROOT = File.expand_path('..', __dir__)
  NOTES_DIR = File.join(ROOT, 'design/notes')
  INDEX_PATH = File.join(NOTES_DIR, 'README.md')
  CLAUDE_PATH = File.join(ROOT, 'CLAUDE.md')
  TERMS_PATH = File.join(ROOT, 'spec/docs/architecture_terms.txt')

  # CLAUDE.md's size budget in bytes (it auto-loads into every agent's
  # context; 142 KB before this split, 42 KB after the 2026-10-10 one)
  BUDGET = 70_000

  SUMMARY = /^<!-- summary -->\n(.*?)\n<!-- \/summary -->$/m
  SUMMARY_MAX = 900
  SUMMARY_LINES = 1..6

  MAP_BEGIN = '<!-- docs:map (generated by `rake docs:index` from design/notes/; edit the notes and spec/docs_index.rb\'s GROUPS) -->'
  MAP_END = '<!-- /docs:map -->'

  # Topic groups in reading order, each note with its label for CLAUDE.md's
  # map (the index uses the note's own title); every note is in exactly one
  GROUPS = {
    'Signal graph' => {
      'graph_nodes' => 'GraphNode DSL', 'graph_io' => 'Graph I/O: recipes, Ruby export, documents', 'library' => 'Library',
      'plan_layer' => 'Plan layer', 'feedback_loops' => 'Feedback loops', 'c_extensions' => 'C extensions', 'sound_guards' => 'Sound guards',
    },
    'Values, time, and channels' => {
      'numbers_lengths_phases' => 'Numbers, lengths, intervals, phases', 'params' => 'Params', 'arg_types' => 'Type-dispatched parameters',
      'curves' => 'Tweening curves', 'tempo_sync' => 'Tempo sync', 'multichannel' => 'Multichannel',
    },
    'Sound' => {
      'oscillators' => 'Oscillators and antialiasing', 'envelopes' => 'Envelopes', 'filters' => 'Filters', 'delays' => 'Delays',
      'chorus' => 'Chorus', 'reverbs' => 'Reverbs', 'dynamics' => 'Dynamics', 'drums' => 'Drum machines', 'sampler' => 'Sampler',
      'textures' => 'Textures', 'granular' => 'Granular and spectral stretch', 'loops' => 'Loop files and tempo-following loops',
      'sq80' => 'SQ-80 voice',
    },
    'Notes and structure' => {
      'sequences' => 'Sequences', 'generative' => 'Generative music', 'midi' => 'MIDI', 'structure' => 'Structure analysis',
    },
    'Session and set' => {
      'arrangement' => 'Arrangement and Session groundwork', 'master_effects' => 'Master effects', 'buses' => 'Buses and sends',
      'cue' => 'CUE and MAIN', 'racks' => 'Racks and typed ports', 'genres' => 'Genre templates',
    },
    'Console, UI, and scripts' => {
      'method_modules' => 'Method modules', 'help' => 'Console help', 'help_tutorial' => 'Help tutorial (design)', 'plotting' => 'Plotting',
      'terminal_ui' => 'Terminal UI', 'sound_design_ui' => 'Sound-design screen', 'scripts' => 'Scripts',
    },
    'Audio I/O' => { 'audio_io' => 'Audio I/O', 'latency_probe' => 'Latency probe' },
  }.freeze

  module_function

  # Note basenames (without .md) on disk, the index left out
  def notes
    Dir[File.join(NOTES_DIR, '*.md')].map { |f| File.basename(f, '.md') }.reject { |n| n == 'README' }.sort
  end

  def note_text(name)
    File.read(File.join(NOTES_DIR, "#{name}.md"))
  end

  def title(name)
    note_text(name)[/\A# (.+)$/, 1] or raise "design/notes/#{name}.md has no '# Title' first line"
  end

  def summary(name)
    note_text(name)[SUMMARY, 1]&.strip
  end

  # Problems with the notes and GROUPS, as messages (empty when fine)
  def note_problems
    grouped = GROUPS.values.flat_map(&:keys)
    problems = []
    (grouped.tally.select { |_, n| n > 1 }.keys).each { |n| problems << "#{n} is in more than one GROUPS entry" }
    (grouped - notes).each { |n| problems << "GROUPS names #{n}, which has no design/notes/#{n}.md" }
    (notes - grouped).each { |n| problems << "design/notes/#{n}.md is in no DocsIndex::GROUPS entry (spec/docs_index.rb)" }
    notes.each do |n|
      s = summary(n)
      next problems << "design/notes/#{n}.md has no <!-- summary --> ... <!-- /summary --> block" if s.nil?

      problems << "design/notes/#{n}.md's summary is #{s.bytesize} bytes (at most #{SUMMARY_MAX})" if s.bytesize > SUMMARY_MAX
      unless SUMMARY_LINES.cover?(s.lines.length)
        problems << "design/notes/#{n}.md's summary has #{s.lines.length} lines (#{SUMMARY_LINES.min}-#{SUMMARY_LINES.max})"
      end
      problems << "design/notes/#{n}.md's summary has a heading" if s.match?(/^#/)
    end
    problems
  end

  def index_text
    out = +<<~HEAD
      # Design notes

      <!-- Generated by `rake docs:index` from each note's summary block; edit the notes (and spec/docs_index.rb's GROUPS), not this file. -->

      One note per subsystem: the design decisions with their dates, measurements, research, and where things render.  Read the topic's note before changing a subsystem, and update the note (its summary block too, then `rake docs:index`) when its behavior changes.
    HEAD
    GROUPS.each do |group, names|
      out << "\n## #{group}\n"
      names.each_key do |n|
        out << "\n### [#{title(n)}](#{n}.md)\n\n#{summary(n)}\n"
      end
    end
    out
  end

  # The topic map in CLAUDE.md: one line per group
  def map_text
    lines = GROUPS.map do |group, names|
      "- #{group}: " + names.map { |n, label| "#{label} (`design/notes/#{n}.md`)" }.join(', ')
    end
    "#{MAP_BEGIN}\n#{lines.join("\n")}\n#{MAP_END}"
  end


  def claude_text
    File.read(CLAUDE_PATH)
  end

  def claude_map
    t = claude_text
    i = t.index(MAP_BEGIN) or return nil
    j = t.index(MAP_END, i) or return nil
    t[i...(j + MAP_END.length)]
  end

  # Messages for generated text that differs from what rake docs:index writes
  def stale_problems
    problems = []
    current = File.exist?(INDEX_PATH) ? File.read(INDEX_PATH) : nil
    problems << 'design/notes/README.md is stale: run `rake docs:index`' if current != index_text
    map = claude_map
    if map.nil?
      problems << "CLAUDE.md has no topic map between #{MAP_BEGIN} and #{MAP_END}"
    elsif map != map_text
      problems << "CLAUDE.md's topic map is stale: run `rake docs:index`"
    end
    problems
  end

  def write!
    raise note_problems.join("\n") unless note_problems.empty?

    File.write(INDEX_PATH, index_text)
    map = claude_map or raise "CLAUDE.md has no topic map markers (#{MAP_BEGIN} ... #{MAP_END})"
    t = claude_text
    File.write(CLAUDE_PATH, t.sub(map) { map_text }) if map != map_text
  end

  # [[section, term], ...] from architecture_terms.txt
  def terms
    section = nil
    File.readlines(TERMS_PATH, chomp: true).filter_map do |l|
      next if l.empty? || l.start_with?('# ')
      if l.start_with?('## ')
        section = l[3..]
        next
      end

      [section, l]
    end
  end

  # Terms appearing in none of CLAUDE.md, the index, and the notes
  def missing_terms
    text = [claude_text, (File.exist?(INDEX_PATH) ? File.read(INDEX_PATH) : ''), *notes.map { |n| note_text(n) }].join("\n")
    terms.reject { |_, t| text.include?(t) }
  end

  # design/notes/x.md references in CLAUDE.md naming notes that don't exist
  def dangling_references
    claude_text.scan(%r{design/notes/([\w-]+)\.md}).flatten.uniq.reject { |n| n == 'README' || notes.include?(n) }
  end

  # [[heading, bytes], ...] of CLAUDE.md's sections, biggest first
  def sections
    t = claude_text
    heads = t.enum_for(:scan, /^##+ .+$/).map { Regexp.last_match }
    heads.each_with_index.map { |m, i|
      stop = heads[i + 1]&.begin(0) || t.length
      [m[0], t[m.begin(0)...stop].bytesize]
    }.sort_by { |_, b| -b }
  end

  # nil within BUDGET, else a message naming the biggest sections
  def size_warning(budget: BUDGET)
    size = claude_text.bytesize
    return nil if size <= budget

    top = sections.first(5).map { |h, b| "#{h} #{(b / 1000.0).round(1)} KB" }
    "CLAUDE.md is #{(size / 1000.0).round(1)} KB, over its #{budget / 1000} KB budget (DocsIndex::BUDGET); " \
      "move architecture into design/notes/ (biggest sections: #{top.join('; ')})"
  end
end
